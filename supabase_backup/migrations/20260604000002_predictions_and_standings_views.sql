-- Add DB objects used by the app but missing from the remote generated types.

CREATE TABLE IF NOT EXISTS public.competition_group_standings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  competition_id integer NOT NULL REFERENCES public.competitions(id) ON DELETE CASCADE,
  season_id integer,
  "group" text NOT NULL,
  team_id integer NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
  position integer NOT NULL,
  fixtures_played integer NOT NULL DEFAULT 0,
  won integer NOT NULL DEFAULT 0,
  drawn integer NOT NULL DEFAULT 0,
  lost integer NOT NULL DEFAULT 0,
  goals_difference integer NOT NULL DEFAULT 0,
  points integer NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (competition_id, season_id, "group", team_id)
);

ALTER TABLE public.competition_group_standings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Authenticated users can read group standings"
  ON public.competition_group_standings;

CREATE POLICY "Authenticated users can read group standings"
  ON public.competition_group_standings FOR SELECT
  TO authenticated
  USING (true);

CREATE OR REPLACE VIEW public.my_predictions_view AS
SELECT
  p.id,
  p.league_member_id,
  lm.league_id,
  p.match_id,
  m.fixture,
  m.competition_id,
  p.home_score AS predicted_home_score,
  p.away_score AS predicted_away_score,
  p.points,
  p.is_finished,
  m.score,
  p.created_at AS prediction_created_at,
  p.updated_at AS prediction_updated_at
FROM public.predictions p
JOIN public.league_members lm ON lm.id = p.league_member_id
JOIN public.matches m ON m.id = p.match_id;
